export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && LANGUAGES.some((l) => l.code === value);
}

export function dirFor(lang: Lang): "ltr" | "rtl" {
  return LANGUAGES.find((l) => l.code === lang)?.dir || "ltr";
}

/** Looks a key up in a language, falling back to English. */
export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  const text = DICTIONARIES[lang]?.[key] ?? en[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] === undefined ? `{${name}}` : String(vars[name]))) : text;
}
